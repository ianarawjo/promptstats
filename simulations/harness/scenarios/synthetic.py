def generate_judge_bias_cell(
    scenario: JudgeBiasSource, rng: np.random.Generator, *, lmm_runs_r: int = JUDGE_BIAS_LMM_RUNS_R,
) -> JudgeBiasCellData:
    """Draw one full replicate's worth of data -- ground truth, LLM-judge
    scores, and human labels -- for every test structure this PPI-mode
    sweep checks at once, all drawn from the same continuing rng stream.

    Truth comes from one representative shape per eval type (_ppi_shape),
    via sample_group_truth -- the same shape catalog and generator
    build_pair_sources/build_multiarm_sources use, so judge-bias scenarios
    are layered on top of a realistic truth model rather than a separate,
    simplified one.

    ``scenario.effect_size`` optionally injects a real difference between
    groups/conditions directly into the truth (group/condition 0 stays at
    baseline, 1 gets +effect_size, 2 gets +2*effect_size, and so on). At
    0.0 (the default, used for checking false-positive rates) there's no
    real difference at all; setting it above 0 turns the same scenario grid
    into a check of how often a real difference gets correctly detected.
    """
    shape = _ppi_shape(scenario.eval_type, scenario.shape_label)
    n1 = scenario.n
    n2 = scenario.n2 if scenario.n2 is not None else scenario.n
    n3 = scenario.n3 if scenario.n3 is not None else scenario.n
    noise1 = scenario.llm_noise
    noise2 = scenario.llm_noise2 if scenario.llm_noise2 is not None else scenario.llm_noise
    noise3 = scenario.llm_noise3 if scenario.llm_noise3 is not None else scenario.llm_noise
    anchor = _ppi_shape_anchor(shape)
    if scenario.eval_type == "likert":
        anchor = _likert_rescale_point(anchor, scenario.likert_max)
    (bias_a, bias_b, bias_c), (slope_a, slope_b, slope_c) = _jb_judge_params_3(scenario)
    es = scenario.effect_size
    cw = scenario.confound_weight

    def _confound(truth: np.ndarray, shift: float) -> float | np.ndarray:
        # 0.0 (every pre-existing scenario, confound_weight defaults to 0)
        # is a fast-path no-op that also avoids consuming any rng draws --
        # keeps every existing scenario's rng stream bit-for-bit unchanged.
        # See JudgeBiasSource.confound_weight/_confound_latent. Consumed by
        # both the affine (_jb_llm/_jb_llm_repeated, as an additive score
        # term) and binary (_jb_llm_binary/_jb_llm_repeated_binary, as a
        # per-item perturbation to the bias/2 flip-probability-skew term)
        # judge models -- confound_weight's appropriate MAGNITUDE differs
        # between the two (score-scale-fraction for the former via
        # _jb_bias_magnitude, flip-probability-scale directly for the
        # latter, matching bias_delta's own convention split -- see
        # build_judge_bias_sources' "confound.*" scenario group).
        return 0.0 if cw == 0.0 else cw * _confound_latent(rng, truth, scenario.confound_truth_corr, shift)

    def _marginal(n: int, effect: float = 0.0) -> np.ndarray:
        """Independent single-group truth draw, optionally shifted by
        `effect`, via sample_group_truth's own `effects` parameter -- which
        shifts the LATENT value (base pass rate for binary, before its
        Bernoulli draw; the pre-rounding/pre-clamping latent Normal for
        likert/grades) before _finish's clamp/round step, the same
        mechanism _repeated (below) already uses correctly for every eval
        type.

        `effect` must be threaded through `effects` rather than added to an
        already-rounded/clamped realized value afterward. For
        continuous/grades (clamp-only, no rounding) this distinction barely
        matters, since clamping is a no-op away from the [0,1]/[0,100]
        boundary. For likert it matters a great deal: rounding-to-nearest-
        integer touches every draw, so adding `effect` to an already-
        rounded integer produces a non-integer "integer + effect" value,
        creating an artificial, near-perfect tie-breaking pattern between
        groups at every shared "level" for any nonzero effect, however
        tiny -- this shows up as a severe power discontinuity specific to
        independent-groups rank tests (MWU/Kruskal; wilcoxon/friedman use
        the unaffected _repeated path) on likert data, jumping from nominal
        Type-I straight to high power at the smallest tested nonzero
        effect_size and then plateauing instead of climbing smoothly. It
        reproduces on pure oracle truth data (a plain scipy.stats.
        mannwhitneyu on the dense truth arrays, zero PPI machinery, zero
        judge noise involved), confirming it's a truth-generation property,
        not a PPI-correction one. Binary is naturally unaffected: adding
        effect to a realized {0,1} outcome would push it outside {0,1}, so
        it must always route through `effects`."""
        return sample_group_truth(
            shape, n, 1, 1, 1.0, rng, effects=np.array([effect]), likert_max=scenario.likert_max,
        )[0, :, 0]

    def _repeated(n: int, n_conditions: int, effects: np.ndarray) -> np.ndarray:
        return sample_group_truth(
            shape, n, 1, n_conditions, scenario.icc, rng, effects=effects, likert_max=scenario.likert_max,
        )[:, :, 0]

    # -- Independent two-group data (ttest, mannwhitney; ttest/ttest_welch
    # also validated on binary -- see _jb_llm_binary. _marginal handles the
    # effect shift correctly for both binary and non-binary -- see its own
    # docstring.) --
    truth_a2 = _marginal(n1)
    truth_b2 = _marginal(n2, es)
    if scenario.eval_type == "binary":
        llm_a2 = _jb_llm_binary(truth_a2, bias_a, noise1, rng, extra=_confound(truth_a2, scenario.confound_shift_a),
                                noise_family=scenario.noise_family, contam_frac=scenario.contam_frac,
                                contam_scale=scenario.contam_scale)
        llm_b2 = _jb_llm_binary(truth_b2, bias_b, noise2, rng, extra=_confound(truth_b2, scenario.confound_shift_b),
                                noise_family=scenario.noise_family, contam_frac=scenario.contam_frac,
                                contam_scale=scenario.contam_scale)
    else:
        llm_a2 = _jb_llm(
            truth_a2, bias_a, noise1, rng, slope=slope_a, anchor=anchor,
            noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
            extra=_confound(truth_a2, scenario.confound_shift_a),
        )
        llm_b2 = _jb_llm(
            truth_b2, bias_b, noise2, rng, slope=slope_b, anchor=anchor,
            noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
            extra=_confound(truth_b2, scenario.confound_shift_b),
        )
    lab_a2 = _jb_labels_independent(
        truth_a2, scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )
    lab_b2 = _jb_labels_independent(
        truth_b2, scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )

    # -- Paired data (wilcoxon; paired_t also validated on binary -- see
    # _jb_llm_repeated_binary) --
    truth_x, truth_y = _repeated(n1, 2, np.array([0.0, es]))
    if scenario.eval_type == "binary":
        llm_x, llm_y = _jb_llm_repeated_binary(
            [truth_x, truth_y], [bias_a, bias_b], [noise1, noise2], rng, corr=scenario.repeated_corr,
            extras=[_confound(truth_x, scenario.confound_shift_a), _confound(truth_y, scenario.confound_shift_b)],
        )
    else:
        llm_x, llm_y = _jb_llm_repeated(
            [truth_x, truth_y], [bias_a, bias_b], [noise1, noise2], [slope_a, slope_b],
            rng, anchor=anchor, corr=scenario.repeated_corr,
            noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
            extras=[_confound(truth_x, scenario.confound_shift_a), _confound(truth_y, scenario.confound_shift_b)],
        )
    lab_x, lab_y = _jb_labels_shared(
        [truth_x, truth_y], scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )

    # -- Independent three-group data (anova_ind) --
    truth_a3 = _marginal(n1)
    truth_b3 = _marginal(n2, es)
    truth_c3 = _marginal(n3, 2 * es)
    llm_a3 = _jb_llm(
        truth_a3, bias_a, noise1, rng, slope=slope_a, anchor=anchor,
        noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
        extra=_confound(truth_a3, scenario.confound_shift_a),
    )
    llm_b3 = _jb_llm(
        truth_b3, bias_b, noise2, rng, slope=slope_b, anchor=anchor,
        noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
        extra=_confound(truth_b3, scenario.confound_shift_b),
    )
    llm_c3 = _jb_llm(
        truth_c3, bias_c, noise3, rng, slope=slope_c, anchor=anchor,
        noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
        extra=_confound(truth_c3, scenario.confound_shift_c),
    )
    lab_a3 = _jb_labels_independent(
        truth_a3, scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )
    lab_b3 = _jb_labels_independent(
        truth_b3, scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )
    lab_c3 = _jb_labels_independent(
        truth_c3, scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )

    # -- Repeated-measures three-group data (anova_rep, friedman, lmm) --
    truth_A, truth_B, truth_C = _repeated(n1, 3, np.array([0.0, es, 2 * es]))
    llm_A, llm_B, llm_C = _jb_llm_repeated(
        [truth_A, truth_B, truth_C], [bias_a, bias_b, bias_c], [noise1, noise2, noise3], [slope_a, slope_b, slope_c],
        rng, anchor=anchor, corr=scenario.repeated_corr,
        noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
        extras=[
            _confound(truth_A, scenario.confound_shift_a), _confound(truth_B, scenario.confound_shift_b),
            _confound(truth_C, scenario.confound_shift_c),
        ],
    )
    lab_A, lab_B, lab_C = _jb_labels_shared(
        [truth_A, truth_B, truth_C], scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )

    # -- 2x2 crossed fixed-factor data (lmm_factorial) --
    (bias_w, bias_x, bias_y, bias_z), (slope_w, slope_x, slope_y, slope_z) = _jb_judge_params_4(scenario)
    truth_W, truth_X, truth_Y, truth_Z = _repeated(n1, 4, np.array([0.0, es, 2 * es, 3 * es]))
    llm_W, llm_X, llm_Y, llm_Z = _jb_llm_repeated(
        [truth_W, truth_X, truth_Y, truth_Z], [bias_w, bias_x, bias_y, bias_z],
        [noise1, noise2, noise3, noise1], [slope_w, slope_x, slope_y, slope_z],
        rng, anchor=anchor, corr=scenario.repeated_corr,
        noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
        extras=[
            _confound(truth_W, scenario.confound_shift_a), _confound(truth_X, scenario.confound_shift_b),
            _confound(truth_Y, scenario.confound_shift_c), _confound(truth_Z, scenario.confound_shift_d),
        ],
    )
    lab_W, lab_X, lab_Y, lab_Z = _jb_labels_shared(
        [truth_W, truth_X, truth_Y, truth_Z], scenario.label_frac, rng,
        mnar=scenario.label_mnar, mnar_strength=scenario.mnar_strength, mnar_mode=scenario.mnar_mode,
    )

    # -- Nested run replication (lmm_runs) --
    a_cols: list[np.ndarray] = []
    b_cols: list[np.ndarray] = []
    c_cols: list[np.ndarray] = []
    for _ in range(lmm_runs_r):
        # Confound redrawn fresh each repeat (not the SAME draw reused
        # across runs) -- consistent with how noise is already redrawn
        # fresh per repeat here; each "run" represents a fresh LLM
        # invocation, which could perceive/exhibit the nuisance covariate
        # (e.g. verbosity) differently each time.
        rA, rB, rC = _jb_llm_repeated(
            [truth_A, truth_B, truth_C], [bias_a, bias_b, bias_c], [noise1, noise2, noise3], [slope_a, slope_b, slope_c],
            rng, anchor=anchor, corr=scenario.repeated_corr,
            noise_family=scenario.noise_family, contam_frac=scenario.contam_frac, contam_scale=scenario.contam_scale,
            extras=[
                _confound(truth_A, scenario.confound_shift_a), _confound(truth_B, scenario.confound_shift_b),
                _confound(truth_C, scenario.confound_shift_c),
            ],
        )
        a_cols.append(rA)
        b_cols.append(rB)
        c_cols.append(rC)
    llm_A_runs = np.column_stack(a_cols)
    llm_B_runs = np.column_stack(b_cols)
    llm_C_runs = np.column_stack(c_cols)

    if scenario.eval_type == "likert":
        # A Likert judge reports on the SAME integer grid the human labels
        # use -- _jb_llm/_jb_llm_repeated build judge scores as an affine
        # distortion of the (already rounded) truth plus continuous noise
        # and never re-discretise, which left the judge on a continuous
        # scale that no rubric-scored judge could actually emit.
        #
        # That gap was not cosmetic. It made the judge used for INFERENCE
        # (continuous, carrying the full bias) a different object from the
        # judge used to REPORT agreement (rounded by
        # measure_judge_alignment, where a sub-half-step bias vanishes),
        # so an alignment metric could read a perfect 1.000 for a judge
        # the tests simultaneously showed producing ~80% false positives.
        # Rounding here makes the two the same judge. It also means a bias
        # smaller than half a scale point genuinely cannot move an integer
        # judge's output, which is a property of ordinal reporting, not an
        # artifact to be corrected away.
        _lo, _hi = 1.0, float(scenario.likert_max)
        _round = lambda a: np.clip(np.rint(a), _lo, _hi)
        llm_a2, llm_b2 = _round(llm_a2), _round(llm_b2)
        llm_x, llm_y = _round(llm_x), _round(llm_y)
        llm_a3, llm_b3, llm_c3 = _round(llm_a3), _round(llm_b3), _round(llm_c3)
        llm_A, llm_B, llm_C = _round(llm_A), _round(llm_B), _round(llm_C)
        llm_W, llm_X = _round(llm_W), _round(llm_X)
        llm_Y, llm_Z = _round(llm_Y), _round(llm_Z)
        llm_A_runs, llm_B_runs, llm_C_runs = (
            _round(llm_A_runs), _round(llm_B_runs), _round(llm_C_runs))

    return JudgeBiasCellData(
        llm_a2=llm_a2, llm_b2=llm_b2, lab_a2=lab_a2, lab_b2=lab_b2, truth_a2=truth_a2, truth_b2=truth_b2,
        llm_x=llm_x, llm_y=llm_y, lab_x=lab_x, lab_y=lab_y, truth_x=truth_x, truth_y=truth_y,
        llm_a3=llm_a3, llm_b3=llm_b3, llm_c3=llm_c3, lab_a3=lab_a3, lab_b3=lab_b3, lab_c3=lab_c3,
        truth_a3=truth_a3, truth_b3=truth_b3, truth_c3=truth_c3,
        llm_A=llm_A, llm_B=llm_B, llm_C=llm_C, lab_A=lab_A, lab_B=lab_B, lab_C=lab_C,
        truth_A=truth_A, truth_B=truth_B, truth_C=truth_C,
        llm_W=llm_W, llm_X=llm_X, llm_Y=llm_Y, llm_Z=llm_Z, lab_W=lab_W, lab_X=lab_X, lab_Y=lab_Y, lab_Z=lab_Z,
        llm_A_runs=llm_A_runs, llm_B_runs=llm_B_runs, llm_C_runs=llm_C_runs,
    )


def estimate_judge_bias_gold_null_values(scenario: JudgeBiasSource, *, n_mc: int = 3000, seed: int = 0) -> dict[str, float]:
    """Estimate, by simulation, what each test's underlying quantity should
    average out to when there's truly no effect -- using only ground-truth
    data (no LLM bias/noise at all) at this scenario's exact sample sizes.
    This is the baseline a bias/coverage check compares against.

    This "true null value" isn't always 0, even though there's no real
    effect: for example, a between-group variance estimator (used by the
    ANOVA-style tests) is built to average out to roughly the noise level
    itself when groups are identical, not to 0 -- a real difference between
    groups would push it higher than that, not away from 0. Estimating it
    by simulation, rather than assuming 0, avoids baking in a wrong
    assumption about what "no effect" looks like for that particular test.

    anova_ind's, anova_rep's, and friedman's gold values are all the
    known-exact constant 0.0 (see bv_gold/rv_gold/frv_gold below), not
    re-derived by simulation: since _repeated/_marginal above never inject
    a condition/group effect (this function only ever computes the
    null-hypothesis baseline), and all three estimators are debiased
    (subtracting the expected-under-H0 floor so they target the clean
    population theta), the correct target is exactly 0.0 -- no simulation
    needed. A raw (undebiased) closed-form null variance, or a
    Monte-Carlo-on-pure-truth re-derivation, are both wrong comparison
    targets once the estimators themselves are debiased: the former
    overstates gold for scenarios with a substantial true effect, and the
    latter can produce pure MC noise around 0 that a noncentral-F-inverted
    CI's lower bound (constrained >= 0) can never cover, manufacturing
    artificially bad coverage. For friedman specifically, calling
    _ppi_friedman_ci with groups_lab=groups (zero noise) makes its
    shrinkage-blend ms_null collapse to a no-op, since the "human" and
    "LLM" rank matrices become identical -- so it degenerates cleanly to
    0.0 too, the same as the other two.

    "wilcoxon"'s gold value is a population midrank-sign quantity (the
    Hodges-Lehmann Walsh-average midrank-sign statistic,
    evalstats.ppi.paired_walsh_midrank_theta), not the population median of
    the paired truth difference -- under heavy ties (e.g. likert's
    integer-rounded truth), the population median can stay locked at
    exactly 0 even under a large, real, classical-Wilcoxon-detectable
    shift, so it isn't a valid comparison target for the estimand
    wilcoxon's own PPI-corrected estimator actually targets -- see that
    function's docstring for the full rationale.

    "ppi_wilson"/"bootstrap_t_single"/"ppi_t_interval_single"/
    "ppi_logit_t_single"'s gold value is the single-arm population mean of
    the "a2" marginal -- the same distribution generate_judge_bias_cell
    draws truth_a2 from -- reusing the diffs2/thetas2 loop's own `a` draw
    rather than a separate MC loop, since it's already exactly that
    quantity.

    "ppi_t_interval"/"ppi_logit_t" target the same paired mean-difference
    estimand as "paired_t"/"mj_floor" (both are closed-form PPI
    corrections for mean(a_i - b_i), differing only in the CI's shape --
    raw vs. logit-transformed -- not the point estimate/null itself), so
    they reuse means_paired.mean() directly."""
    from evalstats.tests import (
        _p_x_gt_y_midrank,
        paired_walsh_midrank_theta,
        _ppi_anova_independent_ci,
        _ppi_anova_repeated_ci,
    )

    rng = np.random.default_rng(seed)
    shape = _ppi_shape(scenario.eval_type, scenario.shape_label)
    n1 = scenario.n
    n2 = scenario.n2 if scenario.n2 is not None else scenario.n
    n3 = scenario.n3 if scenario.n3 is not None else scenario.n

    def _marginal(n: int) -> np.ndarray:
        return sample_group_truth(shape, n, 1, 1, 1.0, rng, likert_max=scenario.likert_max)[0, :, 0]

    def _repeated(n: int, n_conditions: int) -> np.ndarray:
        return sample_group_truth(shape, n, 1, n_conditions, scenario.icc, rng, likert_max=scenario.likert_max)[:, :, 0]

    # For each test family, repeatedly draw pure-truth data and average the
    # test's raw statistic over n_mc draws, to estimate its true null value.
    diffs2 = np.empty(n_mc)  # mean difference (ttest)
    thetas2 = np.empty(n_mc)  # rank-based effect measure (mann-whitney)
    a_means2 = np.empty(n_mc)  # single-arm mean (ppi_wilson, bootstrap_t_single) -- same "a2" draw as diffs2/thetas2
    for i in range(n_mc):
        a = _marginal(n1)
        b = _marginal(n2)
        diffs2[i] = a.mean() - b.mean()
        thetas2[i] = _p_x_gt_y_midrank(a, b) - 0.5
        a_means2[i] = a.mean()

    meds = np.empty(n_mc)  # median paired difference -- kept for reference, no longer wilcoxon's target
    wilcoxon_thetas = np.empty(n_mc)  # P_mid(D>0)-0.5 paired difference (wilcoxon's estimand)
    means_paired = np.empty(n_mc)  # mean paired difference (paired_t)
    for i in range(n_mc):
        x, y = _repeated(n1, 2)
        d = x - y
        meds[i] = float(np.median(d))
        wilcoxon_thetas[i] = paired_walsh_midrank_theta(d)
        means_paired[i] = float(np.mean(d))

    # See this function's docstring: a3/b3/c3 are always drawn from
    # identical distributions here (null-hypothesis baseline only), and the
    # debiased estimator targets the clean population theta directly, so
    # the correct gold value is exactly 0.0 -- no Monte Carlo re-derivation
    # needed (and re-deriving it would reintroduce sampling noise that a
    # non-negative CI lower bound can't legitimately absorb).
    bv_gold = 0.0

    # anova_rep gets the identical treatment as bv_gold above, for the
    # identical reason.
    rv_gold = 0.0

    # friedman gets the same treatment too: calling _ppi_friedman_ci with
    # groups_lab=groups (zero noise) makes its "human" and "LLM" rank
    # matrices identical, so its shrinkage-blend ms_null collapses to a
    # no-op and degenerates cleanly to 0.0 as well.
    frv_gold = 0.0

    return {
        "ttest": float(diffs2.mean()),
        "ttest_welch": float(diffs2.mean()),
        "mw": float(thetas2.mean()),
        "wilcoxon": float(wilcoxon_thetas.mean()),
        "paired_t": float(means_paired.mean()),
        "bayes_bootstrap": float(means_paired.mean()),  # same estimand (paired mean diff) as paired_t
        "bootstrap_t": float(means_paired.mean()),  # same estimand (paired mean diff) as paired_t
        "mj_floor": float(means_paired.mean()),  # same estimand (paired mean diff) as paired_t
        "mj_floor_fixed_lambda": float(means_paired.mean()),  # same estimand as mj_floor, fixed lambda=1
        "bonett_price": float(means_paired.mean()),  # same estimand as mj_floor, Laplace-adjusted interval
        "ppi_t_interval": float(means_paired.mean()),  # same estimand (paired mean diff) as paired_t
        "ppi_logit_t": float(means_paired.mean()),  # same estimand (paired mean diff) as paired_t
        "anova_ind": bv_gold,
        "anova_rep": rv_gold,
        "friedman": frv_gold,
        "kruskal": 0.5,
        "ppi_wilson": float(a_means2.mean()),  # single-arm population mean of "a2" -- same estimand as truth_a2
        "bootstrap_t_single": float(a_means2.mean()),  # same estimand, non-binary construction
        "ppi_t_interval_single": float(a_means2.mean()),  # same estimand, closed-form non-binary construction
        "ppi_logit_t_single": float(a_means2.mean()),  # same estimand, closed-form [lo,hi]-bounded construction
    }
